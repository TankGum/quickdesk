//! macOS clipboard watcher. NSPasteboard has no change notification, so a
//! thread compares its `changeCount` a few times a second and reads only when
//! it moved. Like the other watchers it prefers copied files, then text, then
//! images, and never reads what password managers mark as concealed or
//! transient (the nspasteboard.org conventions).

use std::sync::{Arc, Mutex};
use std::time::Duration;

use objc2::rc::autoreleasepool;
use objc2_app_kit::{
    NSPasteboard, NSPasteboardTypeFileURL, NSPasteboardTypePNG, NSPasteboardTypeString, NSPasteboardTypeTIFF,
    NSWorkspace,
};
use objc2_foundation::NSString;

use super::{file_uri_to_path, set_state, ClipContent, ClipEvent, WatcherState, MAX_IMAGE_BYTES, MAX_TEXT_BYTES};

/// Often enough to feel instant, rare enough to cost nothing.
const INTERVAL: Duration = Duration::from_millis(300);

/// Types that mean "do not record this" (password managers, generated or
/// one-off content).
const SKIP_TYPES: &[&str] =
    &["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];

fn types(pb: &NSPasteboard) -> Vec<String> {
    pb.types().map(|t| t.iter().map(|s| s.to_string()).collect()).unwrap_or_default()
}

/// The paths of copied files (Finder's Copy), if that is what is there.
fn files(pb: &NSPasteboard) -> Option<Vec<String>> {
    let items = pb.pasteboardItems()?;
    // SAFETY: AppKit's constant, valid for the life of the process.
    let file_url = unsafe { NSPasteboardTypeFileURL };
    let paths: Vec<String> = items
        .iter()
        .filter_map(|item| item.stringForType(file_url))
        .filter_map(|url| file_uri_to_path(&url.to_string()))
        .collect();
    (!paths.is_empty()).then_some(paths)
}

/// PNG as offered, or TIFF (what screenshots and Preview put there) as PNG.
fn image_png(pb: &NSPasteboard) -> Option<Vec<u8>> {
    // SAFETY: AppKit's constants, valid for the life of the process.
    let (png, tiff) = unsafe { (NSPasteboardTypePNG, NSPasteboardTypeTIFF) };
    if let Some(data) = pb.dataForType(png) {
        let bytes = data.to_vec();
        return (bytes.len() <= MAX_IMAGE_BYTES).then_some(bytes);
    }
    let data = pb.dataForType(tiff)?.to_vec();
    if data.len() > MAX_IMAGE_BYTES * 4 {
        return None;
    }
    let img = image::load_from_memory_with_format(&data, image::ImageFormat::Tiff).ok()?;
    let mut out = Vec::new();
    img.write_to(&mut std::io::Cursor::new(&mut out), image::ImageFormat::Png).ok()?;
    (out.len() <= MAX_IMAGE_BYTES).then_some(out)
}

/// Read what is on the clipboard now. `None`: nothing we keep, or a secret.
fn read(pb: &NSPasteboard) -> Option<ClipContent> {
    let types = types(pb);
    if types.iter().any(|t| SKIP_TYPES.contains(&t.as_str())) {
        return None;
    }
    let has = |name: &NSString| types.iter().any(|t| t == &name.to_string());
    // SAFETY: AppKit's constants, valid for the life of the process.
    let (file_url, string) = unsafe { (NSPasteboardTypeFileURL, NSPasteboardTypeString) };
    if has(file_url) {
        if let Some(paths) = files(pb) {
            return Some(ClipContent::Files(paths));
        }
    }
    if has(string) {
        if let Some(text) = pb.stringForType(string).map(|s| s.to_string()) {
            if !text.trim().is_empty() && text.len() <= MAX_TEXT_BYTES {
                return Some(ClipContent::Text(text));
            }
        }
    }
    image_png(pb).map(|bytes| ClipContent::Image { mime: "image/png".into(), bytes })
}

/// The app in front, which is almost always the one that just copied.
fn front_app() -> Option<String> {
    NSWorkspace::sharedWorkspace().frontmostApplication()?.localizedName().map(|n| n.to_string())
}

pub(super) fn spawn(on_event: impl Fn(ClipEvent) + Send + 'static, state: Arc<Mutex<WatcherState>>) -> &'static str {
    let started = std::thread::Builder::new().name("qd-clipboard".into()).spawn(move || {
        let pb = NSPasteboard::generalPasteboard();
        // Do not record whatever was on the clipboard before we started.
        let mut last = pb.changeCount();
        set_state(&state, WatcherState::Running);
        loop {
            std::thread::sleep(INTERVAL);
            // Each round's Objective-C temporaries are released right away.
            autoreleasepool(|_| {
                let count = pb.changeCount();
                if count == last {
                    return;
                }
                last = count;
                if let Some(content) = read(&pb) {
                    on_event(ClipEvent { content, source_app: front_app() });
                }
            });
        }
    });
    if let Err(e) = started {
        tracing::error!(error = %e, "clipboard watcher thread");
    }
    "nspasteboard"
}
